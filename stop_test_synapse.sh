#!/usr/bin/env bash
# ↑ 这一行叫 shebang，意思是告诉 Linux：用哪个解释器来执行本文件。
# /usr/bin/env bash 的好处是：它会在系统的 PATH 环境变量里寻找 bash，
# 而不是写死成 /bin/bash。不同服务器 bash 的位置可能不完全一致，用 env 更通用。
# 你用 “bash stop_mpnet_by_run_id.sh …” 执行时，这一行也能保证脚本按 bash 语法解析，
# 避免被 sh 或其他 shell 解析导致语法不兼容（比如数组、[[ ]]、set -e 等行为不同）。

set -euo pipefail
# ↑ 这一行是 bash 脚本常见的“安全模式”，用来减少脚本静默失败的概率。
# -e：只要某个命令返回非 0（失败），脚本就立刻退出，避免继续执行造成误杀或误操作。
# -u：如果你引用了一个未定义变量（比如 RUN_ID 没传），脚本会报错退出，而不是当成空字符串继续跑。
# -o pipefail：管道命令中任何一个环节失败，整个管道都算失败；否则默认只看最后一个命令的返回值。
# 这些设置能防止你因为参数没传、文件不存在、命令失败而误 kill 到不该 kill 的进程。

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# ↑ 这一行的目的：获取“脚本所在目录”的绝对路径，并保存到 PROJECT_DIR 变量。
# BASH_SOURCE[0] 是当前脚本文件名；dirname 获取它的目录；cd 进去后再 pwd 得到绝对路径。
# 为什么不直接用 pwd？因为你执行脚本时，当前工作目录可能在任何地方（比如你在家目录运行脚本），
# pwd 得到的是“你执行命令时的位置”，而不是工程目录。我们要的是工程目录，才能稳定定位 logs 文件夹。
# 这样不管你在哪个目录运行 stop 脚本，它都能找到正确的 logs/ 和 pid 文件，不会误读别的路径。



RUN_ID="${1:-}"
# ↑ 这一行表示：从脚本的第 1 个参数读取 run_id，保存到 RUN_ID 变量。
# ${1:-} 的意思是：如果用户没有传第一个参数，就给 RUN_ID 一个默认空字符串。
# 例如你执行：bash stop_mpnet_by_run_id.sh synapse_2026-...，那 RUN_ID 就是这个字符串。
# 为什么我们用 run_id 而不是直接用 pid 来 stop？因为 pid 只是一个数字，无法表达“这是哪一次实验”，
# run_id 是你人为定义的“业务唯一标识”，它可以对应日志、参数、训练记录，更容易精确定位要停的那一轮。

[ -n "${RUN_ID}" ] || exit 1
# ↑ 这一行是参数校验：如果 RUN_ID 为空（用户没传参数），就直接退出并返回状态码 1。
# [ -n "xxx" ] 表示字符串长度非 0；如果条件不成立，右边的 exit 1 执行。
# 这样做的原因：没有 run_id 的情况下，脚本无法知道你想停止哪一次训练，
# 如果继续往下跑可能会拼出错误的 pid 文件路径，导致读错文件甚至误 kill。
# 这里不输出 echo 是你要求的“精简”，但退出码能让你在命令行通过 $? 判断错误原因。

PID_FILE="${RUN_ID}.pid"
# ↑ 这一行根据 run_id 拼出 pid 文件路径。
# 你的启动脚本会生成：${RUN_ID}.pid，里面只存一个纯数字 PID。
# 这样“run_id -> pid 文件 -> pid”形成了稳定映射：你只要记住 run_id，就能精确找到对应进程。
# 这比用 grep 进程名更安全，因为 grep 可能匹配到别人的训练脚本或你自己另外一轮训练。
# 另外，pid 文件名里包含 run_id，也能避免多个实验互相覆盖同一个 pid 文件。

[ -f "${PID_FILE}" ] || exit 2
# ↑ 这一行校验 pid 文件是否存在。
# -f 表示“是一个普通文件”。如果不存在就退出并返回 2。
# 为什么要检查？因为如果 pid 文件不存在，说明：
# 1）你传错了 run_id；或 2）启动脚本没成功写 pid 文件；或 3）logs 被清理了。
# 在这种情况下继续执行会导致 cat 读取失败，或者 PID 为空，再往下 kill 会出问题。
# 所以这里直接退出是最安全的行为。你后续只需要 ls logs/train_*.pid 找到正确的 run_id 即可。

PID="$(cat "${PID_FILE}" | tr -d ' \n')"
# ↑ 这一行从 pid 文件里读取 PID，并做清理：去掉空格和换行，确保 PID 是纯数字字符串。
# cat "${PID_FILE}" 会输出文件内容，比如 "12345\n"；tr -d ' \n' 会删除空格和换行。
# 为什么要这样做？因为文本文件通常以换行结尾，如果不去掉换行，有些场景下 PID 变量会带不可见字符，
# 导致 kill 命令行为异常或者比较字符串时出错。
# 注意：这里 pid 文件只应该存一个数字（我们启动脚本就是 echo "${PID}" > pidfile），
# 所以读出来应该是单个 PID。这个 PID 是 OS 级唯一标识（在进程存活期间唯一）。

[ -n "${PID}" ] || exit 3
# ↑ 这一行校验 PID 是否为空。
# 如果 pid 文件是空的、或读取失败、或内容不是你预期的数字，就直接退出并返回 3。
# 为什么要检查？因为如果 PID 为空，你执行 kill -TERM "" 可能会报错，
# 更糟的是某些脚本写法可能会变成 kill -TERM （没有参数）导致不可预期行为。
# 这里强制要求 PID 必须存在，是为了把风险前置，让错误尽早暴露，不让脚本继续做危险动作。

kill -0 "${PID}" 2>/dev/null || { rm -f "${PID_FILE}"; exit 0; }
# ↑ 这一行是“只检查进程是否存在”，不会真正杀掉进程。
# kill -0 的语义是：向 PID 发送信号 0（不存在的信号），系统只做权限和存在性检查：
# - 如果返回 0，说明这个 PID 的进程存在，并且你有权限对它发信号；
# - 如果返回非 0，说明进程不存在或无权限。
# 我们把错误输出丢到 /dev/null，是为了不输出系统报错（你要求精简）。
# 如果进程不存在，我们直接 exit 0，表示“目标已经不在了”，这是一种幂等行为：重复 stop 不会报错。

ENV_RUN_ID="$(tr '\0' '\n' < "/proc/${PID}/environ" | sed -n 's/^RUN_ID=//p' | head -n 1)"  
# 从environ =取RUN_ID

[ "${ENV_RUN_ID}" = "${RUN_ID}" ] || exit 4
# RUN_ID 不匹配：拒绝停止（防 pid 复用误杀）

kill -TERM "${PID}"
# ↑ 这一行才是真正执行“优雅停止”。
# SIGTERM（TERM）是标准的终止信号，意思是“请进程尽快退出”，属于可捕获信号。
# 你的 Python 训练脚本如果写得规范，收到 TERM 之后可以执行清理逻辑，比如：
# - 保存 checkpoint（如果你代码里处理了 signal）
# - 关闭文件句柄、释放资源
# - 正常退出
# 这比 kill -9 更安全，因为 kill -9 会直接强制终止进程，可能导致日志不完整、权重文件写到一半损坏。
# 所以“优雅停止”的正确顺序永远是先 TERM，再视情况决定是否需要 KILL。

for _ in {1..10}; do
   # 最多等 10 秒
  kill -0 "${PID}" 2>/dev/null || { rm -f "${PID_FILE}"; exit 0; }
  sleep 1
done

kill -KILL "${PID}" 2>/dev/null || true
rm -f "${PID_FILE}"

